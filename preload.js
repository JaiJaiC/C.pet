const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("cpet", {
  toggleNote: () => ipcRenderer.invoke("note:toggle"),
  hideNote: () => ipcRenderer.invoke("note:hide"),
  setNoteHeight: (height) => ipcRenderer.invoke("note:set-height", Number(height)),
  startWindowDrag: (details) => ipcRenderer.send("window:start-drag", details),
  updateWindowDrag: () => ipcRenderer.send("window:update-drag"),
  stopWindowDrag: () => ipcRenderer.send("window:stop-drag"),
  nudgePet: (details) => ipcRenderer.send("window:nudge-pet", details),
  nudgePetByKey: (x, y) => ipcRenderer.send("window:nudge-pet-key", { x, y }),
  setPetBounds: (visualBounds) => ipcRenderer.send("window:set-pet-bounds", visualBounds),
  setIgnoreMouse: (ignore) => ipcRenderer.invoke("window:set-ignore-mouse", Boolean(ignore)),
  setAlwaysOnTop: (enabled) => ipcRenderer.invoke("window:set-always-on-top", Boolean(enabled)),
  resetPetPosition: () => ipcRenderer.invoke("window:reset-pet-position"),
  broadcastSettings: (patch) => ipcRenderer.invoke("settings:broadcast", patch),
  getSettings: () => ipcRenderer.invoke("settings:get"),
  getVersion: () => ipcRenderer.invoke("app:get-version"),
  listTools: () => ipcRenderer.invoke("tools:list"),
  launchTool: (toolId) => ipcRenderer.invoke("tools:launch", String(toolId)),
  getMonitorStats: () => ipcRenderer.invoke("monitor:get"),
  performAction: (action) => ipcRenderer.invoke("action:perform", String(action)),
  setQuickShortcut: (accelerator) => ipcRenderer.invoke("shortcut:set", String(accelerator)),
  setLaunchAtLogin: (enabled) => ipcRenderer.invoke("app:set-launch-at-login", Boolean(enabled)),
  getLaunchAtLogin: () => ipcRenderer.invoke("app:get-launch-at-login"),
  listCompletedTasks: () => ipcRenderer.invoke("database:list-completed"),
  completeTask: (text, list) => ipcRenderer.invoke("database:complete-task", String(text), String(list)),
  deleteCompletedTask: (id) => ipcRenderer.invoke("database:delete-completed", id),
  clearCompletedTasks: () => ipcRenderer.invoke("database:clear-completed"),
  onSettingsChanged: (callback) => ipcRenderer.on("settings:changed", (_event, patch) => callback(patch)),
  onQuickEntry: (callback) => ipcRenderer.on("shortcut:quick-entry", () => callback()),
  onActionRequested: (callback) => ipcRenderer.on("action:requested", (_event, action) => callback(action)),
  openInEdge: (url) => ipcRenderer.invoke("link:open-edge", url),
  quit: () => ipcRenderer.invoke("window:quit"),
});
